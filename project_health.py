# ////////////////////////////////////////////////////////////// คำนวณ BMI เริ่ม

def cal_bmi(weight_kg, height_cm):
    height_m = height_cm / 100.0
    if height_m <= 0:
        print("ส่วนสูงต้องมากกว่า 0")
        return None
    else:
        return weight_kg / (height_m * height_m)
        # ////////////////////////////////////////////////////////////// คำนวณ BMI จบ


# ////////////////////////////////////////////////////////////// BMI เริ่ม


def classify_bmi(bmi):
    if bmi >= 30.0:
        return "อ้วนมาก"
    elif 25.0 <= bmi <= 29.9:
        return "อ้วน"
    elif 23.0 <= bmi <= 24.9:
        return "น้ำหนักเกิน"
    elif 18.6 <= bmi <= 22.9:
        return "น้ำหนักปกติ"
    else:
        return "ผอมเกินไป"


